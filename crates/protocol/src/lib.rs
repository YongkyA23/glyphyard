//! Messages between the desktop app and the server (`/api/v1`).

use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};

pub const INSTALL_KEY_HEADER: &str = "X-Install-Key";

/// An `Activate` ack error when the font is not in that computer's library: `"{CODE}: {ps_name}{SUFFIX}"`.
/// The server recognises it and old desktops send the same text, so the wording must not change.
pub const FONT_NOT_HERE_CODE: &str = "file_missing";
pub const FONT_NOT_HERE_SUFFIX: &str = " is not in this library";

/// Longest font name and note of an `Event::FontRequested`, in characters. The desktop refuses longer text; the
/// server cuts it.
pub const FONT_REQUEST_NAME_MAX: usize = 200;
pub const FONT_REQUEST_NOTE_MAX: usize = 1000;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RegisterRequest {
    /// Random id generated by the app on first launch.
    pub install_id: String,
    pub name: String,
    pub os: String,
    pub app_version: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RegisterResponse {
    pub token: String,
    pub name: String,
    pub next_name_change: Option<DateTime<Utc>>,
    pub policy: Policy,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Policy {
    pub name_change_days: u32,
    pub allow_connection_edit: bool,
    pub notify_admin_changes: bool,
    /// Admin-set branding; empty = Glyphyard's own. Defaulted so a newer app still reads an older server.
    #[serde(default)]
    pub brand_name: String,
    /// `#rrggbb` or empty.
    #[serde(default)]
    pub brand_color: String,
    /// `data:image/...;base64,...` (PNG, JPEG, WebP or SVG) or empty.
    #[serde(default)]
    pub brand_logo: String,
    /// Argon2 PHC string of the admin's connection unlock password, or empty when none is set. The desktop app keeps
    /// it so an admin can unlock Settings › Connection on a locked computer even when the server can't be reached.
    #[serde(default)]
    pub connection_password_hash: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct NameChange {
    pub name: String,
}

/// 200 on success; 409 with the same body when the limit has not passed yet.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct NameStatus {
    pub name: String,
    pub next_name_change: Option<DateTime<Utc>>,
}

#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct FontRef {
    /// BLAKE3 of the file.
    pub hash: String,
    pub ps_name: String,
    pub family: String,
    pub style: String,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Source {
    User,
    Admin,
    ProjectSet,
    Library,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum Event {
    FontActivated { font: FontRef, source: Source },
    /// `was_admin` marks an override: the user turned off a font an admin turned on.
    FontDeactivated { font: FontRef, source: Source, was_admin: bool },
    ActivationFailed { font: FontRef, reason: String },
    ProjectSetToggled { name: String, on: bool, fonts: u32 },
    OrganizeApplied { changes: u32 },
    DuplicatesReport { duplicates: u32, version_conflicts: u32, name_clashes: u32 },
    RepairRan { removed: u32, reregistered: u32 },
    /// "I need this font": a request to the admin. A server older than this event rejects it (422), and the
    /// desktop drops only that event.
    FontRequested { name: String, #[serde(default)] note: Option<String> },
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TimedEvent {
    pub at: DateTime<Utc>,
    #[serde(flatten)]
    pub event: Event,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EventBatch {
    pub events: Vec<TimedEvent>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ActiveFont {
    #[serde(flatten)]
    pub font: FontRef,
    pub source: Source,
}

/// Full list of active fonts, sent after startup reconcile.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FontSnapshot {
    pub active: Vec<ActiveFont>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct LibraryFile {
    pub hash: String,
    pub filename: String,
    pub size: u64,
    pub ps_name: String,
    pub family: String,
    pub license: String,
    pub blocked: bool,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum CommandKind {
    Activate { font: FontRef },
    Deactivate { font: FontRef },
    /// Download from the shared library, optionally turning it on.
    Deliver { file: LibraryFile, activate: bool },
    /// Deactivate everywhere and refuse to activate.
    Block { ps_name: String, hash: Option<String> },
    Unblock { ps_name: String },
    /// Show the auto-organize preview; the user decides.
    OrganizeRequest,
    PolicyChanged { policy: Policy },
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Command {
    pub id: i64,
    #[serde(flatten)]
    pub kind: CommandKind,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ServerMessage {
    Command(Command),
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ClientMessage {
    Ack { id: i64, ok: bool, error: Option<String> },
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn command_wire_format_is_flat() {
        let msg = ServerMessage::Command(Command {
            id: 7,
            kind: CommandKind::Deactivate {
                font: FontRef { hash: "h".into(), ps_name: "Fraunces-Regular".into(), family: "Fraunces".into(), style: "Regular".into() },
            },
        });
        let json = serde_json::to_value(&msg).unwrap();
        assert_eq!(json["type"], "command");
        assert_eq!(json["kind"], "deactivate");
        assert_eq!(json["id"], 7);
        let back: ServerMessage = serde_json::from_value(json).unwrap();
        assert!(matches!(back, ServerMessage::Command(Command { id: 7, .. })));
    }

    #[test]
    fn font_request_round_trips() {
        let e = TimedEvent { at: Utc::now(), event: Event::FontRequested { name: "Söhne Buch".into(), note: Some("for the Acme deck".into()) } };
        let json = serde_json::to_value(&e).unwrap();
        assert_eq!(json["kind"], "font_requested");
        assert_eq!(json["name"], "Söhne Buch");
        let back: TimedEvent = serde_json::from_value(json).unwrap();
        assert_eq!(back.event, e.event);
        // An older desktop never sends `note`; a missing one reads as none.
        let bare: Event = serde_json::from_value(serde_json::json!({ "kind": "font_requested", "name": "X" })).unwrap();
        assert_eq!(bare, Event::FontRequested { name: "X".into(), note: None });
    }
}
